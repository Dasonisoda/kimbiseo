YAWNS = [("하암, 잠깐 졸았네요.", "잠깐 졸았네요."), ("하아아암~ 졸려요.", "졸려요."), ("(하품) 네, 알겠습니다.", "네, 알겠습니다."),
         ("네, 알겠습니다. 하암, 졸려요.", "네, 알겠습니다. 졸려요."), ("하품이 나와요.", "하품이 나와요."), ("함께 가요", "함께 가요")]


def run_cases():
    rows = []
    for group, cases in CASES.items():
        for src, want in cases:
            got = T.normalize(src)
            rows.append((group, src, want, got, got == want))
    return rows


def test_table():
    rows = run_cases()
    bad = [(s, w, g) for _, s, w, g, ok in rows if not ok]
    assert len(rows) >= 50, f"시험 문장이 50개보다 적음({len(rows)})"
    assert not bad, "변환이 다름 " + " / ".join(f"{s!r} → {g!r} (기대 {w!r})" for s, w, g in bad[:8]) + (f" 외 {len(bad) - 8}개" if len(bad) > 8 else "")


def test_numbers():
    for n, w in [(0, "영"), (10, "십"), (11, "십일"), (110, "백십"), (10000, "만"), (10001, "만일"), (20000, "이만"), (1000000, "백만")]:
        assert T.sino(n) == w, (n, T.sino(n), w)
    for n, w in [(1, "한"), (2, "두"), (20, "스무"), (21, "스물한"), (99, "아흔아홉"), (100, "백"), (101, "백한"), (119, "백열아홉"), (120, "백이십")]:
        assert T.native(n) == w, (n, T.native(n), w)


def test_yawn_and_plain_text():
    for t, w in YAWNS:
        assert T.normalize(t) == w, (t, T.normalize(t), w)
    for t in ["안녕하세요, 반가워요.", "오늘 날씨가 참 좋네요!", "네, 알겠습니다. 바로 해 볼게요."]:
        assert T.normalize(t) == t, ("숫자 없는 글은 그대로", t, T.normalize(t))


def test_no_control_chars():
    """읽기 변환 결과에 제어문자가 섞이지 않는다(예전 판은 '!~' 뒤에 제어문자 하나가 남았음)."""
    for _, src, _, got, _ in run_cases():
        assert not any(ord(c) < 32 for c in got), (src, got)
    assert not any(ord(c) < 32 for c in T.normalize("좋아요!~ 그럼요.")), "제어문자"


def test_idempotent_on_spoken_text():
    """이미 읽기로 바꾼 글을 한 번 더 넣어도 그대로 — 본체가 바꾼 글을 목소리 서버가 다시 받아도 안전."""
    for _, src, _, got, ok in run_cases():
        if ok:
            assert T.normalize(got) == got, (src, got, T.normalize(got))


def test_split_sentences():
    sp = T.split_sentences("안녕하세요. 오늘은 맑아요! 그런데요, 아주 긴 문장은 이렇게 쉼표가 여러 개 있으면, 적당한 곳에서 한 번 더 나눠서, 먼저 말할 수 있게 합니다.")
    assert len(sp) >= 3 and any(x.endswith(",") for x in sp) and max(len(x) for x in sp) <= 60, sp
    sp2 = T.split_sentences("네, 알겠습니다. 지금 바로 확인해 볼게요. 작업 끝났습니다. 결과는 화면에 띄워 두었어요. 확인 부탁드립니다.")
    assert not any(len(x) < 15 for x in sp2) and max(len(x) for x in sp2) <= 60, sp2


def main():
    if "--table" in sys.argv:
        g0 = None
        for group, src, want, got, ok in run_cases():
            if group != g0:
                print(f"\n[{group}]")
                g0 = group
            print(("  " if ok else "✗ ") + f"{src}  →  {got}" + ("" if ok else f"   (기대: {want})"))
        return 0
    fails = 0
    for k, f in list(globals().items()):
        if k.startswith("test_") and callable(f):
            try:
                f()
                print("됨  ", k)
            except Exception as ex:  # noqa: BLE001
                fails += 1
                print("안 됨", k, ex.__class__.__name__, ex)
    print(f"변환 표 {sum(len(v) for v in CASES.values())}문장 · 실패", fails)
    return 1 if fails else 0


if __name__ == "__main__":
    sys.exit(main())
